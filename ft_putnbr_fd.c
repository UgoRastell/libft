#include "libft.h"

void	ft_putnbr(int nb)
{
	char	result_modulo;

	if (nb == -2147483648)
	{
		write(1, "-2147483648", 12);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb = nb * -1;
	}
	if (nb >= 10)
		ft_putnbr(nb / 10);
	result_modulo = (nb % 10) + '0';
	write(1, &result_modulo, 1);
}
